// Release-transition regression in an isolated tree; never modifies the real manifest/docs.
import assert from "node:assert/strict";
import { mkdtemp, mkdir, cp, symlink, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = fileURLToPath(new URL("../", import.meta.url));
const fixture = await mkdtemp(join(tmpdir(), "precisekit-docs-sync-"));
await mkdir(join(fixture, "scripts"));
for (const entry of ["docs", "dist", "README.md", "package.json", "CHANGELOG.md"]) await cp(join(root, entry), join(fixture, entry), { recursive: true });
for (const entry of ["sync-docs.mjs", "measure-bundle.mjs", "docs-text.mjs"]) await cp(join(root, "scripts", entry), join(fixture, "scripts", entry));
await symlink(join(root, "node_modules"), join(fixture, "node_modules"), "dir");
const manifest = JSON.parse(await readFile(join(fixture, "package.json"), "utf8"));
manifest.version = "0.5.1-test.1";
manifest.description = "Future </script> description regression proof.";
manifest.branding = { displayName: "PreciseKit Next", tagline: "Exact & tested", seoTitle: "Next & safe", seoDescription: "Future SEO description" };
await writeFile(join(fixture, "package.json"), JSON.stringify(manifest));
const history = await readFile(join(fixture, "CHANGELOG.md"), "utf8");
await writeFile(join(fixture, "CHANGELOG.md"), `# Changelog\n\n## ${manifest.version}\n\n- Release transition regression proof.\n\n${history}`);
const originalSite = await readFile(join(fixture, "docs/index.html"), "utf8");
await writeFile(join(fixture, "docs/index.html"), originalSite.replace('<div class="faq">', '<div class="faq"><details>\n<summary>Multiline &amp;lt;title&amp;gt;</summary>\n<p>Literal &lt;/script&gt;\n text.</p>\n</details>'));
const run = () => spawnSync(process.execPath, [join(fixture, "scripts/sync-docs.mjs")], { cwd: fixture, encoding: "utf8" });
let result = run();
assert.ifError(result.error);
assert.equal(result.status, 0, result.stderr);
const html = await readFile(join(fixture, "docs/index.html"), "utf8");
assert.ok(html.includes(`Version ${manifest.version}`));
assert.ok(html.includes(`Release ${manifest.version}`));
assert.ok(html.includes(`"softwareVersion":"${manifest.version}"`));
assert.ok(html.includes('<title>Next &amp; safe</title>'));
assert.ok(html.includes('name="description" content="Future SEO description"'));
assert.ok(html.includes('property="og:title" content="Next &amp; safe"'));
assert.ok(html.includes('name="twitter:description" content="Future SEO description"'));
assert.ok(html.includes('"name":"PreciseKit Next"'));
assert.ok((await readFile(join(fixture, "README.md"), "utf8")).includes("Future &lt;/script&gt; description regression proof."));
const jsonLd = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map(([, json]) => JSON.parse(json));
assert.equal(jsonLd.find(entry => entry["@type"] === "SoftwareSourceCode").description, manifest.description);
assert.deepEqual(jsonLd.find(entry => entry["@type"] === "FAQPage").mainEntity[0], {
  "@type": "Question", name: "Multiline &lt;title&gt;", acceptedAnswer: { "@type": "Answer", text: "Literal </script> text." },
});
assert.ok(html.includes('\\u003c/script>'), "JSON-LD must not terminate its script element");
const repositoryMetadata = JSON.parse(await readFile(join(fixture, ".github/repository-metadata.json"), "utf8"));
assert.equal(repositoryMetadata.description, manifest.description);
assert.ok(html.includes("<li>Release transition regression proof.</li>"));
assert.ok(html.includes("utilities 0.4.2 to PreciseKit 0.5.0"), "migration history must stay fixed");
assert.ok(html.includes("0.4.2, historical"), "comparison history must stay fixed");
assert.ok(!html.includes("<li>Renamed the package"), "future release must not reuse the rebrand summary");
// Bundle chart: the previous release stays a historical row while the new version becomes the current row.
const rows = [...html.matchAll(/<li class="size-row is-(historical|current)" data-version="([^"]+)">/g)].map(([, state, rowVersion]) => `${rowVersion}:${state}`);
assert.deepEqual(rows, ["0.3.4:historical", "0.4.2:historical", "0.5.0:historical", `${manifest.version}:current`], "bundle chart must keep history and add the new current row");
assert.ok(html.includes("0.5.0, historical:") && html.includes(`${manifest.version}, current:`), "bundle chart text alternatives must name each row");
assert.ok(html.includes("86.5 kB minified") && html.includes("Brotli not measured"), "historical figures must come from docs/bundle-history.json");
const widths = [...html.matchAll(/<rect class="size-fill" width="(\d+)"/g)].map(([, width]) => Number(width));
assert.equal(Math.max(...widths), 1000, "the largest bar must span the shared scale");
assert.ok(html.includes(`<meta property="og:image" content="${manifest.homepage}assets/og-image.png">`), "social image URL must derive from the homepage");
result = run();
assert.equal(result.status, 0, result.stderr);
assert.equal(await readFile(join(fixture, "docs/index.html"), "utf8"), html, "sync must be idempotent");
await writeFile(join(fixture, "docs/index.html"), html.replace("<!-- package-metadata:bundle-history -->", ""));
result = run();
assert.notEqual(result.status, 0, "missing bundle history marker must fail");
assert.match(result.stderr, /Missing package metadata marker: bundle-history/);
await writeFile(join(fixture, "docs/index.html"), html);
const historyPath = join(fixture, "docs/bundle-history.json");
const historyFile = await readFile(historyPath, "utf8");
await writeFile(historyPath, historyFile.replace('"schemaVersion": 1', '"schemaVersion": 2'));
result = run();
assert.notEqual(result.status, 0, "unsupported bundle history schema must fail");
assert.match(result.stderr, /schemaVersion must be 1/);
await writeFile(historyPath, historyFile.replace('"kind": "historical"', '"kind": "current"'));
result = run();
assert.notEqual(result.status, 0, "history entries must stay historical");
await writeFile(historyPath, historyFile);
await writeFile(join(fixture, "docs/index.html"), html.replace("<!-- package-metadata:footer-version -->", ""));
result = run();
assert.notEqual(result.status, 0, "missing metadata marker must fail");
assert.match(result.stderr, /Missing package metadata marker: footer-version/);
await writeFile(join(fixture, "docs/index.html"), html + "<!-- /package-metadata:footer-version -->");
result = run();
assert.notEqual(result.status, 0, "duplicate metadata end marker must fail");
assert.match(result.stderr, /Duplicate package metadata end marker: footer-version/);
await writeFile(join(fixture, "docs/index.html"), html + '<link rel="canonical" href="https://stale.example/">');
result = run();
assert.notEqual(result.status, 0, "duplicate canonical metadata must fail");
assert.match(result.stderr, /canonical URL must occur exactly once/);
console.log("Docs release transition, historical preservation, idempotence and missing-marker rejection verified.");
