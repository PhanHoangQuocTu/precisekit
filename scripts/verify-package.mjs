import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const metadataUrl = process.argv[2]
  ? pathToFileURL(resolve(process.argv[2]))
  : new URL("../package.json", import.meta.url);
const metadata = JSON.parse(await readFile(metadataUrl, "utf8"));
assert.equal(metadata.name, "@fatdevcon/precisekit", "package identity must match the PreciseKit release");
assert.match(metadata.version, /^0\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/, "package version must be a valid pre-1.0 SemVer release");
assert.equal(metadata.dependencies, undefined, "the package must have no runtime dependencies");
assert.equal(metadata.peerDependencies, undefined);
const esm = await import(metadata.name);
const cjs = require(metadata.name);
assert.equal(typeof Intl.Segmenter, "function");
for (const api of [esm, cjs]) {
  assert.equal(api.formatCompactNumber(12500), "12.5K");
  assert.equal(api.formatCurrency(1234.5, "USD"), "$1,234.50");
  assert.equal(api.formatPercent(0.125), "12.5%");
  assert.equal(api.formatBytes(1536, { base: 1024 }), "1.5 KiB");
  assert.deepEqual(api.getCountryCurrencies("VN"), ["VND"]);
  assert.equal(api.shortenString("abcdefghijklxyzc"), "abcd...xyzc");
  assert.equal(api.truncateText("👨‍👩‍👧‍👦🇻🇳abcd", 3, { ellipsis: "…" }), "👨‍👩‍👧‍👦🇻🇳…");
  assert.equal(api.slugify("Đặng Thị Tú"), "dang-thi-tu");
  assert.equal(api.summary(0.1, 0.2), 0.3);
  assert.equal(api.formatDate(new Date(2026, 9, 3), "yyyy-MM-dd"), "2026-10-03");
  assert.equal(api.formatDate("2026-10-03", "yyyy-MM-dd"), "2026-10-03");
  assert.equal(api.kebabCase("helloWorld"), "hello-world");
  assert.equal(api.formatDuration(3723000), "1h 2m 3s");
  assert.deepEqual(api.difference([1, 2, 3], [2]), [1, 3]);
  assert.deepEqual(api.deepMerge({ a: { b: 1 } }, { a: { c: 2 } }), { a: { b: 1, c: 2 } });
  assert.equal(api.isEmail("user@example.com"), true);
  assert.equal(typeof api.debounce, "function");
  assert.equal(typeof api.withRetry, "function");
  assert.equal(typeof api.wait, "function");
  assert.equal(api.getTimeZoneOffset(new Date("2026-01-15T12:00:00Z"), "Asia/Ho_Chi_Minh"), 420);
  assert.equal(api.getTimeZoneOffset(new Date("2026-01-15T12:00:00Z"), "Asia/Ho_Chi_Minh", { unit: "hours" }), 7);
  assert.equal(typeof api.formatInTimeZone, "function");
  assert.equal(api.formatDate(new Date("2026-01-15T17:30:00Z"), "yyyy-MM-dd HH:mm xxx", { timeZone: "Asia/Ho_Chi_Minh" }), "2026-01-16 00:30 +07:00");
  assert.equal(api.formatDate("2026-01-15", "EEEE, do MMMM yyyy"), "Thursday, 15th January 2026");
  assert.equal(api.parseISO("2026-10-03T10:30:15.250+07:00").toISOString(), "2026-10-03T03:30:15.250Z");
  assert.equal(api.formatDate(api.addMonths("2026-01-31", 1), "yyyy-MM-dd"), "2026-02-28");
  assert.equal(api.differenceInCalendarDays("2026-01-01", "2025-01-01"), 365);
  assert.equal(api.formatDate(api.addYears("2024-02-29", 1), "yyyy-MM-dd"), "2025-02-28");
  assert.equal(api.isWithinInterval(2, { start: 1, end: 2 }), true);
  assert.deepEqual(api.enumerate(["a", "b"], 1), [[1, "a"], [2, "b"]]);
  assert.equal(api.sumBy([{ amount: "0.1" }, { amount: "0.2" }], (item) => item.amount), "0.3");
  assert.equal(api.isNode(), true);
  assert.equal(api.safeJsonParse("{\"ok\":true}").ok, true);
  assert.equal(api.buildQueryString({ tag: ["a", "b"] }), "tag=a&tag=b");
  assert.equal(api.parseDuration("1h 2m 3s"), 3723000);
  assert.equal(api.parseBytes("1.5 GB"), 1500000000);
  assert.equal(api.parseBytes("1.5 QB", { bigint: true }), 1500000000000000000000000000000n);
  assert.deepEqual(api.setByPath({ a: 1 }, "b.c[0]", true), { a: 1, b: { c: [true] } });
  assert.equal(api.escapeRegExp("a.b*"), "a\\.b\\*");
  assert.equal(api.strip("  nguyen van an  "), "nguyen van an");
  assert.equal(api.lstrip("🌍hello🌍", "🌍"), "hello🌍");
  assert.equal(api.rstrip("🌍hello🌍", "🌍"), "🌍hello");
  assert.equal(api.title(" đẶNG vĂN lÂM-o'CONNOR "), " Đặng Văn Lâm-O'connor ");
  assert.equal(api.firstChar("👨‍👩‍👧‍👦hello"), "👨‍👩‍👧‍👦");
  assert.equal(api.lastChar("hello👍🏽"), "👍🏽");
  assert.equal(api.capitalize("hELLO WORLD"), "HELLO WORLD");
  assert.equal(api.safeToNumber(" 1e3 "), 1000);
  assert.equal(api.safeToNumber("9007199254740993"), null);
  assert.equal(api.safeToNumber("1e-999"), null);
  assert.equal(api.safeToInteger("1.00000000000000001"), null);
  assert.equal(api.safeToInteger(" -123 "), -123);
  assert.equal(api.safeToBigInt("9007199254740993"), 9007199254740993n);
  assert.equal(api.safeToBigInt(9007199254740992), null);
  assert.equal(api.safeToBoolean(" FALSE "), false);
  assert.equal(api.safeToString({ a: 1 }), '{"a":1}');
  assert.equal(api.safeToString({ toJSON() { throw new Error("bad data"); } }), null);
  assert.equal(api.round(1.005, 2), 1.01);
  assert.equal(api.summary("100000000000000000000000000000", "1"), "100000000000000000000000000001");
  assert.equal(api.multiply(2n ** 64n, 2n ** 64n), 2n ** 128n);
  assert.equal(api.factorial(25n), 15511210043330985984000000n);
  assert.equal(api.isPrime(2n ** 127n - 1n), true);
  assert.equal(api.formatBytes("1500000000000000000000000000000"), "1.5 QB");
  assert.throws(() => api.multiply(1e200, 1e200), (error) => error instanceof RangeError && error.code === "ERR_OVERFLOW");
  assert.throws(() => api.summary(NaN, 1), (error) => error instanceof TypeError && error.code === "ERR_INVALID_NUMBER");
  assert.equal(api.toMinorUnits("123.45", { currency: "USD" }), 12345n);
  assert.equal(api.fromMinorUnits(12345n, { currency: "USD" }), "123.45");
  assert.deepEqual(api.allocateMoney("10.00", [1, 1, 1], { currency: "USD" }), ["3.34", "3.33", "3.33"]);
  assert.deepEqual(api.calculateTax("100", "0.08", { currency: "USD", mode: "exclusive" }), { subtotal: "100.00", tax: "8.00", total: "108.00" });
  assert.equal(api.applyDiscount("100", { type: "percentage", value: "15" }, { currency: "USD" }).final, "85.00");
  assert.equal(api.parseLocalizedNumber("1.234,56", { locale: "de-DE" }), "1234.56");
  assert.equal(api.parseLocalizedCurrency("$1,234.56", { locale: "en-US", currency: "USD" }), "1234.56");
  assert.equal(api.parseLocalizedPercent("12.5%", { locale: "en-US" }), "0.125");
  const normalize = input => api.normalizeRecord(input, { name: api.strip, age: api.safeToInteger });
  assert.deepEqual(normalize({ name: " Minh ", age: "21" }), { success: true, data: { name: "Minh", age: 21 } });
  assert.equal(api.normalizeArray([{ name: "Minh", age: "invalid" }], normalize).success, false);
  assert.deepEqual(await api.mapConcurrent([1, 2], async n => n * 2, { concurrency: 1 }), [2, 4]);
  assert.deepEqual(await api.mapSettledConcurrent([1], n => n, { concurrency: 1 }), [{ status: "fulfilled", value: 1 }]);
  assert.deepEqual(await api.batchAsync([1, 2, 3], batch => batch.length, { batchSize: 2 }), [2, 1]);
  assert.equal(api.isBusinessDay("2026-12-25", { holidays: ["2026-12-25"] }), false);
  assert.equal(api.addBusinessDays("2026-12-24", 1, { holidays: ["2026-12-25"] }), "2026-12-28");
  assert.equal(api.differenceInBusinessDays("2026-12-24", "2026-12-29", { holidays: ["2026-12-25"] }), 2);
  assert.equal(api.nextBusinessDay("2026-12-25"), "2026-12-28");
  assert.equal(api.isSafeRedirectUrl("//evil.example"), false);
  assert.equal(api.getSafeRedirectTarget("https://evil.example", { fallback: "/" }), "/");
  assert.deepEqual(api.redactSensitiveFields({ password: "secret" }, { keys: ["password"] }), { password: "[REDACTED]" });
  assert.equal(api.sanitizeUrlForLogging("https://example.com/?token=secret"), "https://example.com/?token=%5BREDACTED%5D");
}
assert.deepEqual(Object.keys(esm).filter(key => key !== "default").sort(), Object.keys(cjs).sort());
console.log(`Package exports verified (ESM + CommonJS) on ${globalThis.Bun ? "Bun " + Bun.version : "Node " + process.version}.`);
