site = replaceMarker(site, "release-summary", `<ul>${releaseSummary}</ul>`);
site = replaceMarker(site, "footer-version", `Version ${version}`);
site = replaceMarker(site, "bundle-fact", `<dt>${kb(full.gzip)}</dt><dd>Full-root browser bundle, minified + gzip. Named imports are measured separately. <a href="#size">Compare releases</a>.</dd>`);
